-- 1. Criar a tabela de Categorias (Tabela independente)
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    -- Campos de auditoria (Auditable)
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT uq_categories_name UNIQUE (name)
);

-- Índice único da Categoria
CREATE UNIQUE INDEX idx_category_name ON categories (name);


-- 2. Criar a tabela de Produtos (Depende da tabela de categorias)
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(2000),
    price NUMERIC(12, 2) NOT NULL,
    stock_quantity INTEGER DEFAULT 0 NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    category_id BIGINT NOT NULL,

    -- Campos de auditoria (Auditable)
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT fk_products_on_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

-- Índices mapeados na entidade Product
CREATE INDEX idx_product_name ON products (name);
CREATE INDEX idx_product_active ON products (active);


-- 3. Criar a tabela auxiliar de Imagens (ElementCollection da entidade Product)
CREATE TABLE product_images (
    product_id BIGINT NOT NULL,
    image_url VARCHAR(500),
    image_order INTEGER NOT NULL, -- Gerado pela anotação @OrderColumn

    CONSTRAINT pk_product_images PRIMARY KEY (product_id, image_order),
    CONSTRAINT fk_product_images_on_product FOREIGN KEY (product_id) REFERENCES products (id)
);
